"""Crop the saved OSM survey into a 1.5-metre gameplay grid.

The source coordinates come from build-map.py. Geometry is retained beyond the
crop edge when its bounding box intersects the crop so roads and buildings do
not acquire artificial cut edges. The game renderer clips to the map bounds.
"""

import json
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "reference/map-data.json"
DESTINATION = ROOT / "assets/city-geography.js"
CROP = (16, 4, 136, 178)
OFFSET = (14, 2)
WIDTH, HEIGHT = 124, 178
GRID_SCALE = 4
TILE_METRES = 1.5
ROAD_KINDS = {
    "primary", "secondary", "tertiary", "residential", "living_street",
    "unclassified", "service", "pedestrian", "footway", "path", "steps",
}


def intersects(points):
    """Whether the feature's bounds overlap the original tile crop."""
    if not points:
        return False
    west, north, east, south = CROP
    return (
        max(p[0] for p in points) >= west
        and min(p[0] for p in points) <= east
        and max(p[1] for p in points) >= north
        and min(p[1] for p in points) <= south
    )


def translated(points):
    return [[round((x - OFFSET[0]) * GRID_SCALE, 2),
             round((y - OFFSET[1]) * GRID_SCALE, 2)]
            for x, y in points]


def bounds(points):
    x = math.floor(min(p[0] for p in points))
    y = math.floor(min(p[1] for p in points))
    return {
        "x": x,
        "y": y,
        "w": math.ceil(max(p[0] for p in points)) - x,
        "h": math.ceil(max(p[1] for p in points)) - y,
    }


def squared_distance(point, start, end):
    dx, dy = end[0] - start[0], end[1] - start[1]
    length = dx * dx + dy * dy
    if not length:
        return (point[0] - start[0]) ** 2 + (point[1] - start[1]) ** 2
    t = max(0, min(1, ((point[0] - start[0]) * dx
                      + (point[1] - start[1]) * dy) / length))
    return (point[0] - start[0] - t * dx) ** 2 + (point[1] - start[1] - t * dy) ** 2


def simplify(points, tolerance=0.04):
    """Simplify source lines by at most 0.24 metres before 1.5 m gridding."""
    if len(points) <= 2:
        return points
    index, distance = max(
        ((i, squared_distance(points[i], points[0], points[-1]))
         for i in range(1, len(points) - 1)),
        key=lambda pair: pair[1],
    )
    if distance <= tolerance * tolerance:
        return [points[0], points[-1]]
    return simplify(points[:index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)


def compile_geography(source):
    roads = []
    for feature in source["roads"]:
        points, kind = feature["points"], feature["kind"]
        campus_path = kind in {"footway", "path"} and any(y < 55 for _, y in points)
        if not intersects(points) or not (kind in ROAD_KINDS or campus_path):
            continue
        roads.append({
            "id": feature["id"],
            "name": feature.get("name", ""),
            "kind": kind,
            "points": translated(simplify(points)),
            "crossing": feature.get("crossing", False),
            "area": kind == "pedestrian" and len(points) > 3 and points[0] == points[-1],
        })

    buildings = []
    for feature in source["buildings"]:
        if not intersects(feature["points"]):
            continue
        points = translated(feature["points"])
        buildings.append({
            "id": feature["id"],
            "name": feature.get("name", ""),
            "branch": feature.get("branch", ""),
            "points": points,
            "bbox": bounds(points),
            **{key: feature[key] for key in ("buildingType", "minHeight", "height") if key in feature},
        })

    parks = []
    for feature in source["parks"]:
        if not intersects(feature["points"]):
            continue
        points = translated(feature["points"])
        parks.append({"name": feature.get("name", ""), "points": points,
                      "bbox": bounds(points)})

    def locations(features):
        return [dict(feature,
                     x=round((feature["x"] - OFFSET[0]) * GRID_SCALE),
                     y=round((feature["y"] - OFFSET[1]) * GRID_SCALE))
                for feature in features if intersects([[feature["x"], feature["y"]]])]

    return {
        "w": WIDTH * GRID_SCALE, "h": HEIGHT * GRID_SCALE,
        "metresPerTile": TILE_METRES,
        "roads": roads, "parks": parks, "buildings": buildings,
        "exits": locations(source["exits"]), "pois": locations(source["pois"]),
    }


if __name__ == "__main__":
    geography = compile_geography(json.loads(SOURCE.read_text()))
    DESTINATION.write_text(
        "/* Generated by scripts/build-city.py.\n"
        " * Geographic data: © OpenStreetMap contributors, ODbL 1.0.\n"
        " * https://www.openstreetmap.org/copyright\n"
        " * 1.5 metres per tile (four cells per source tile); crop x=16..136, y=4..178.\n"
        " */\nconst CITY_GEOGRAPHY = "
        + json.dumps(geography, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    print(f"City: {geography['w']} × {geography['h']}, {geography['metresPerTile']} m/tile")
    for category in ("roads", "parks", "buildings", "exits", "pois"):
        print(f"{category}: {len(geography[category])}")
